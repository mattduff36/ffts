CREATE OR REPLACE FUNCTION public.guard_queued_schedule_visit_mutation_v1()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_visit_id UUID := CASE WHEN TG_OP = 'DELETE' THEN OLD.id ELSE NEW.id END;
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM public.schedule_visit_backlog AS backlog
    WHERE backlog.visit_id = v_visit_id
  ) THEN
    IF TG_OP = 'DELETE' THEN
      RETURN OLD;
    END IF;
    RETURN NEW;
  END IF;

  IF TG_OP = 'DELETE' AND (
    NOT EXISTS (
      SELECT 1 FROM public.schedule_jobs AS job WHERE job.id = OLD.job_id
    )
  ) THEN
    -- Parent job deletion owns this cascade; the backlog marker cascades too.
    RETURN OLD;
  END IF;

  RAISE EXCEPTION 'VISIT_QUEUED'
    USING ERRCODE = 'P0001';
END;
$$;

