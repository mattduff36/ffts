CREATE OR REPLACE FUNCTION public.lock_and_guard_schedule_assignment_backlog_v1()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_visit_id UUID;
  v_old_visit_id UUID;
  v_new_visit_id UUID;
BEGIN
  IF TG_OP IN ('UPDATE', 'DELETE') THEN
    v_old_visit_id := OLD.visit_id;
  END IF;
  IF TG_OP IN ('INSERT', 'UPDATE') THEN
    v_new_visit_id := NEW.visit_id;
  END IF;

  -- Lock both sides of a move in UUID order so enqueue, move, and delete
  -- serialize without deadlocks or stale assignment counts.
  FOR v_visit_id IN
    SELECT candidate
    FROM (
      VALUES (v_old_visit_id), (v_new_visit_id)
    ) AS visit_ids(candidate)
    WHERE candidate IS NOT NULL
    GROUP BY candidate
    ORDER BY candidate
  LOOP
    PERFORM 1
    FROM public.schedule_visits AS visit
    WHERE visit.id = v_visit_id
    FOR UPDATE;
  END LOOP;

  IF v_new_visit_id IS NOT NULL AND EXISTS (
    SELECT 1
    FROM public.schedule_visit_backlog AS backlog
    WHERE backlog.visit_id = v_new_visit_id
  ) THEN
    RAISE EXCEPTION 'VISIT_QUEUED'
      USING ERRCODE = 'P0001';
  END IF;

  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.lock_and_guard_schedule_assignment_backlog_v1()
  FROM PUBLIC, anon, authenticated;

