    END IF;
    RETURN QUERY
    SELECT
      (v_existing.result->>'visit_id')::UUID,
      (v_existing.result->>'job_id')::UUID,
      (v_existing.result->>'starts_at')::TIMESTAMPTZ,
      (v_existing.result->>'ends_at')::TIMESTAMPTZ,
      (v_existing.result->>'job_start_date')::DATE,
      (v_existing.result->>'job_end_date')::DATE;
    RETURN;
  END IF;

  SELECT *
  INTO v_visit
  FROM public.schedule_visits AS visit
  WHERE visit.id = p_visit_id;

  IF v_visit.id IS NULL THEN
    RAISE EXCEPTION 'VISIT_NOT_FOUND'
      USING ERRCODE = 'P0001';
  END IF;

  SELECT *
  INTO v_job_seed
  FROM public.schedule_jobs AS job
  WHERE job.id = v_visit.job_id;

  IF v_job_seed.id IS NULL THEN
    RAISE EXCEPTION 'JOB_NOT_FOUND'
      USING ERRCODE = 'P0001';
  END IF;

  v_target_date := (p_starts_at AT TIME ZONE 'Europe/London')::DATE;

  IF v_job_seed.source_type = 'quote' THEN
    -- Match the authoritative Quote -> job -> visit lock order used by sync.
    SELECT *
    INTO v_quote
    FROM public.quotes AS quote
    WHERE quote.id = v_job_seed.quote_id
    FOR UPDATE;

    IF v_quote.id IS NULL
       OR v_quote.is_latest_version IS DISTINCT FROM TRUE
       OR v_quote.commercial_status IS DISTINCT FROM 'open'
       OR v_quote.start_date IS NULL THEN
      RAISE EXCEPTION 'QUOTE_NOT_SCHEDULABLE'
        USING ERRCODE = 'P0001';
    END IF;

    SELECT *
    INTO v_job
    FROM public.schedule_jobs AS job
    WHERE job.id = v_visit.job_id
    FOR UPDATE;
    IF v_job.source_type <> 'quote'
       OR v_job.quote_id IS DISTINCT FROM v_quote.id THEN
      RAISE EXCEPTION 'JOB_CHANGED'
        USING ERRCODE = 'P0001';
    END IF;
  ELSE
    SELECT *
    INTO v_job
    FROM public.schedule_jobs AS job
    WHERE job.id = v_visit.job_id
    FOR UPDATE;
    IF v_job.source_type = 'quote'
       OR v_job.status IN ('completed', 'cancelled') THEN
      RAISE EXCEPTION 'JOB_NOT_SCHEDULABLE'
        USING ERRCODE = 'P0001';
    END IF;
  END IF;

  SELECT *
  INTO v_visit
  FROM public.schedule_visits AS visit
  WHERE visit.id = p_visit_id
  FOR UPDATE;
  IF v_visit.id IS NULL OR v_visit.job_id <> v_job.id THEN
    RAISE EXCEPTION 'VISIT_NOT_FOUND'
      USING ERRCODE = 'P0001';
  END IF;
  IF v_visit.status IN ('completed', 'cancelled') THEN
    RAISE EXCEPTION 'VISIT_NOT_QUEUEABLE'
      USING ERRCODE = 'P0001';
  END IF;

  SELECT *
  INTO v_backlog
  FROM public.schedule_visit_backlog AS backlog
  WHERE backlog.visit_id = p_visit_id
  FOR UPDATE;
  IF v_backlog.visit_id IS NULL THEN
    RAISE EXCEPTION 'VISIT_NOT_QUEUED'
      USING ERRCODE = 'P0001';
  END IF;
  v_resolved_ends := p_starts_at
    + (v_backlog.original_ends_at - v_backlog.original_starts_at);
  IF (p_starts_at AT TIME ZONE 'Europe/London')::DATE
     <> (v_resolved_ends AT TIME ZONE 'Europe/London')::DATE THEN
    RAISE EXCEPTION 'VISIT_MUST_FIT_ONE_DAY'
      USING ERRCODE = 'P0001';
  END IF;

  IF v_job.source_type = 'quote' THEN
    v_new_start := LEAST(v_quote.start_date, v_target_date);
    v_new_end := GREATEST(
      v_quote.start_date
        + GREATEST(COALESCE(v_quote.estimated_duration_days, 1), 1) - 1,
      v_target_date
    );

    UPDATE public.quotes
    SET
      start_date = v_new_start,
      estimated_duration_days = (v_new_end - v_new_start) + 1,
      updated_by = p_actor_user_id,
      updated_at = NOW()
    WHERE quotes.id = v_quote.id;

    SELECT *
    INTO v_job
    FROM public.schedule_jobs AS job
    WHERE job.id = v_visit.job_id;
  ELSE
    v_new_start := LEAST(v_job.start_date, v_target_date);
    v_new_end := GREATEST(v_job.end_date, v_target_date);

    UPDATE public.schedule_jobs
    SET
      start_date = v_new_start,
      end_date = v_new_end,
      updated_by = p_actor_user_id,
      updated_at = NOW()
    WHERE schedule_jobs.id = v_job.id
    RETURNING * INTO v_job;
  END IF;

  -- Remove the marker inside this transaction before updating the immutable
  -- visit snapshot. Other transactions cannot observe the deletion until commit.
  DELETE FROM public.schedule_visit_backlog AS backlog
  WHERE backlog.visit_id = v_visit.id;

  UPDATE public.schedule_visits
  SET
    starts_at = p_starts_at,
    ends_at = v_resolved_ends,
    updated_by = p_actor_user_id,
    updated_at = NOW()
  WHERE schedule_visits.id = v_visit.id;

  INSERT INTO public.schedule_visit_transition_events (
    visit_id,
    job_id,
    action,
    actor_user_id,
    from_starts_at,
    from_ends_at,
    to_starts_at,
    to_ends_at
  )
  VALUES (
    v_visit.id,
    v_visit.job_id,
    'schedule',
    p_actor_user_id,
    v_visit.starts_at,
    v_visit.ends_at,
    p_starts_at,
    v_resolved_ends
  );

  v_result := jsonb_build_object(
    'visit_id', v_visit.id,
    'job_id', v_visit.job_id,
    'starts_at', p_starts_at,
    'ends_at', v_resolved_ends,
    'job_start_date', v_job.start_date,
    'job_end_date', v_job.end_date
  );

  INSERT INTO public.schedule_visit_transition_requests (
    request_id,
    action,
    visit_id,
    actor_user_id,
    input_hash,
    result
  )
  VALUES (
    p_request_id,
    'schedule',
    v_visit.id,
    p_actor_user_id,
    v_input_hash,
    v_result
  );

  RETURN QUERY
  SELECT
    v_visit.id,
    v_visit.job_id,
    p_starts_at,
    v_resolved_ends,
    v_job.start_date,
    v_job.end_date;
END;
$$;

