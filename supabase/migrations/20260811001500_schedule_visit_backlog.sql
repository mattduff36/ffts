-- Keep Quote synchronization backlog-aware so range contractions do not try
-- to mutate an immutable queued visit snapshot.
CREATE OR REPLACE FUNCTION public.sync_operational_quote_schedule_job()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  resolved_reference TEXT;
  resolved_title TEXT;
  resolved_end_date DATE;
  resolved_job_id UUID;
  is_schedulable BOOLEAN;
BEGIN
  is_schedulable :=
    NEW.is_latest_version = TRUE
    AND NEW.commercial_status = 'open'
    AND NEW.start_date IS NOT NULL;

  IF NOT is_schedulable THEN
    UPDATE public.schedule_jobs
    SET
      status = 'cancelled',
      updated_by = COALESCE(NEW.updated_by, NEW.created_by),
      updated_at = NOW()
    WHERE quote_id = NEW.id
      AND source_type = 'quote';
    RETURN NEW;
  END IF;

  resolved_reference := COALESCE(
    NULLIF(BTRIM(NEW.base_quote_reference), ''),
    NEW.quote_reference
  );
  resolved_title := COALESCE(
    NULLIF(BTRIM(NEW.subject_line), ''),
    NULLIF(BTRIM(NEW.project_description), ''),
    'Quoted work'
  );
  resolved_end_date :=
    NEW.start_date + GREATEST(COALESCE(NEW.estimated_duration_days, 1), 1) - 1;

  UPDATE public.schedule_jobs
  SET
    job_reference = resolved_reference,
    title = resolved_title,
    description = NEW.project_description,
    site_address = NEW.site_address,
    status = CASE WHEN NEW.status = 'in_progress' THEN 'in_progress' ELSE 'scheduled' END,
    start_date = NEW.start_date,
    end_date = resolved_end_date,
    estimated_duration_minutes = NEW.estimated_duration_minutes,
    customer_id = NEW.customer_id,
    customer_site_id = NEW.customer_site_id,
    updated_by = COALESCE(NEW.updated_by, NEW.created_by),
    updated_at = NOW()
  WHERE quote_id = NEW.id
    AND source_type = 'quote'
  RETURNING id INTO resolved_job_id;

  IF resolved_job_id IS NULL THEN
    INSERT INTO public.schedule_jobs (
      job_reference,
      title,
      description,
      site_address,
      status,
      source_type,
      start_date,
      end_date,
      estimated_duration_minutes,
      quote_id,
      customer_id,
      customer_site_id,
      created_by,
      updated_by
    )
    VALUES (
      resolved_reference,
      resolved_title,
      NEW.project_description,
      NEW.site_address,
      CASE WHEN NEW.status = 'in_progress' THEN 'in_progress' ELSE 'scheduled' END,
      'quote',
      NEW.start_date,
      resolved_end_date,
      NEW.estimated_duration_minutes,
      NEW.id,
      NEW.customer_id,
      NEW.customer_site_id,
      NEW.created_by,
      COALESCE(NEW.updated_by, NEW.created_by)
    )
    ON CONFLICT (job_reference) DO UPDATE
    SET
      title = EXCLUDED.title,
      description = EXCLUDED.description,
      site_address = EXCLUDED.site_address,
      status = EXCLUDED.status,
      source_type = 'quote',
      start_date = EXCLUDED.start_date,
      end_date = EXCLUDED.end_date,
      estimated_duration_minutes = EXCLUDED.estimated_duration_minutes,
      quote_id = EXCLUDED.quote_id,
      customer_id = EXCLUDED.customer_id,
      customer_site_id = EXCLUDED.customer_site_id,
      updated_by = EXCLUDED.updated_by,
      updated_at = NOW()
    WHERE public.schedule_jobs.source_type = 'quote'
    RETURNING id INTO resolved_job_id;
  END IF;

  IF resolved_job_id IS NULL THEN
    RAISE EXCEPTION
      'Scheduling job reference % is already owned by a non-Quote job.',
      resolved_reference;
  END IF;

  UPDATE public.schedule_visits AS visit
  SET
    status = 'cancelled',
    updated_by = COALESCE(NEW.updated_by, NEW.created_by),
    updated_at = NOW()
  WHERE visit.job_id = resolved_job_id
    AND visit.status <> 'cancelled'
    AND (
      (visit.starts_at AT TIME ZONE 'Europe/London')::DATE < NEW.start_date
      OR (visit.starts_at AT TIME ZONE 'Europe/London')::DATE > resolved_end_date
    )
    AND NOT EXISTS (
      SELECT 1
      FROM public.schedule_visit_backlog AS backlog
      WHERE backlog.visit_id = visit.id
    );

  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.sync_operational_quote_schedule_job()
  FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.enqueue_schedule_visit_v1(
  p_request_id UUID,
  p_visit_id UUID,
  p_expected_fingerprint TEXT,
  p_actor_user_id UUID
)
RETURNS TABLE (
  visit_id UUID,
  job_id UUID,
  assignment_count INTEGER,
  queued_at TIMESTAMPTZ
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_visit public.schedule_visits%ROWTYPE;
  v_job_seed public.schedule_jobs%ROWTYPE;
  v_job public.schedule_jobs%ROWTYPE;
  v_quote public.quotes%ROWTYPE;
  v_existing public.schedule_visit_transition_requests%ROWTYPE;
  v_fingerprint TEXT;
  v_assignment_count INTEGER;
  v_queued_at TIMESTAMPTZ := NOW();
  v_input_hash TEXT;
  v_result JSONB;
BEGIN
  IF p_request_id IS NULL OR p_visit_id IS NULL OR p_actor_user_id IS NULL THEN
    RAISE EXCEPTION 'A request, visit, and actor are required.';
  END IF;
  IF NULLIF(BTRIM(COALESCE(p_expected_fingerprint, '')), '') IS NULL THEN
    RAISE EXCEPTION 'A visit fingerprint is required.';
  END IF;

  v_input_hash := md5(
    p_visit_id::TEXT || '|enqueue|' || p_expected_fingerprint
  );
  PERFORM pg_advisory_xact_lock(hashtextextended(p_request_id::TEXT, 0));

  SELECT *
  INTO v_existing
  FROM public.schedule_visit_transition_requests AS transition
  WHERE transition.request_id = p_request_id;

  IF FOUND THEN
    IF v_existing.action <> 'enqueue'
       OR v_existing.visit_id <> p_visit_id
       OR v_existing.input_hash <> v_input_hash THEN
      RAISE EXCEPTION 'REQUEST_ID_REUSED'
        USING ERRCODE = 'P0001';
    END IF;
    RETURN QUERY
    SELECT
      (v_existing.result->>'visit_id')::UUID,
      (v_existing.result->>'job_id')::UUID,
      (v_existing.result->>'assignment_count')::INTEGER,
      (v_existing.result->>'queued_at')::TIMESTAMPTZ;
    RETURN;
  END IF;

  SELECT *
  INTO v_visit
  FROM public.schedule_visits AS visit
  WHERE visit.id = p_visit_id;

  IF v_visit.id IS NULL THEN
    RAISE EXCEPTION 'VISIT_NOT_FOUND'
      USING ERRCODE = 'P0001';
  END IF;

  SELECT *
  INTO v_job_seed
  FROM public.schedule_jobs AS job
  WHERE job.id = v_visit.job_id;
  IF v_job_seed.id IS NULL THEN
    RAISE EXCEPTION 'JOB_NOT_FOUND'
      USING ERRCODE = 'P0001';
  END IF;

  IF v_job_seed.source_type = 'quote' THEN
    SELECT *
    INTO v_quote
    FROM public.quotes AS quote
    WHERE quote.id = v_job_seed.quote_id
    FOR UPDATE;
    IF v_quote.id IS NULL
       OR v_quote.is_latest_version IS DISTINCT FROM TRUE
       OR v_quote.commercial_status IS DISTINCT FROM 'open'
       OR v_quote.start_date IS NULL THEN
      RAISE EXCEPTION 'QUOTE_NOT_SCHEDULABLE'
        USING ERRCODE = 'P0001';
    END IF;

    SELECT *
    INTO v_job
    FROM public.schedule_jobs AS job
    WHERE job.id = v_visit.job_id
    FOR UPDATE;
    IF v_job.source_type <> 'quote'
       OR v_job.quote_id IS DISTINCT FROM v_quote.id THEN
      RAISE EXCEPTION 'JOB_CHANGED'
        USING ERRCODE = 'P0001';
    END IF;
  ELSE
    SELECT *
    INTO v_job
    FROM public.schedule_jobs AS job
    WHERE job.id = v_visit.job_id
    FOR UPDATE;
    IF v_job.source_type = 'quote'
       OR v_job.status IN ('completed', 'cancelled') THEN
      RAISE EXCEPTION 'JOB_NOT_SCHEDULABLE'
        USING ERRCODE = 'P0001';
    END IF;
  END IF;

  -- Assignment mutation RPCs lock their row before visit rows. Match that
  -- order here to avoid row-lock/visit-lock inversion during enqueue.
  PERFORM employee.id
  FROM public.schedule_employee_assignments AS employee
  WHERE employee.visit_id = p_visit_id
  ORDER BY employee.id
  FOR UPDATE;
  PERFORM plant.id
  FROM public.schedule_plant_assignments AS plant
  WHERE plant.visit_id = p_visit_id
  ORDER BY plant.id
  FOR UPDATE;

  SELECT *
  INTO v_visit
  FROM public.schedule_visits AS visit
  WHERE visit.id = p_visit_id
  FOR UPDATE;
  IF v_visit.id IS NULL OR v_visit.job_id <> v_job.id THEN
    RAISE EXCEPTION 'VISIT_NOT_FOUND'
      USING ERRCODE = 'P0001';
  END IF;
  IF v_visit.status IN ('completed', 'cancelled') THEN
    RAISE EXCEPTION 'VISIT_NOT_QUEUEABLE'
      USING ERRCODE = 'P0001';
  END IF;
  IF EXISTS (
    SELECT 1
    FROM public.schedule_visit_backlog AS backlog
    WHERE backlog.visit_id = p_visit_id
  ) THEN
    RAISE EXCEPTION 'VISIT_ALREADY_QUEUED'
      USING ERRCODE = 'P0001';
  END IF;

  v_fingerprint := public.schedule_visit_backlog_fingerprint_v1(p_visit_id);
  IF v_fingerprint IS DISTINCT FROM p_expected_fingerprint THEN
    RAISE EXCEPTION 'STALE_VISIT_PREVIEW'
      USING ERRCODE = 'P0001';
  END IF;

  SELECT (
    (SELECT COUNT(*) FROM public.schedule_employee_assignments AS employee
      WHERE employee.visit_id = p_visit_id)
    +
    (SELECT COUNT(*) FROM public.schedule_plant_assignments AS plant
      WHERE plant.visit_id = p_visit_id)
  )::INTEGER
  INTO v_assignment_count;

  INSERT INTO public.schedule_visit_backlog (
    visit_id,
    original_starts_at,
    original_ends_at,
    queued_by,
    queued_at
  )
  VALUES (
    v_visit.id,
    v_visit.starts_at,
    v_visit.ends_at,
    p_actor_user_id,
    v_queued_at
  );

  DELETE FROM public.schedule_employee_assignments AS employee
  WHERE employee.visit_id = p_visit_id;
  DELETE FROM public.schedule_plant_assignments AS plant
  WHERE plant.visit_id = p_visit_id;

  INSERT INTO public.schedule_visit_transition_events (
    visit_id,
    job_id,
    action,
    actor_user_id,
    assignment_count,
    from_starts_at,
    from_ends_at
  )
  VALUES (
    v_visit.id,
    v_visit.job_id,
    'enqueue',
    p_actor_user_id,
    v_assignment_count,
    v_visit.starts_at,
    v_visit.ends_at
  );

  v_result := jsonb_build_object(
    'visit_id', v_visit.id,
    'job_id', v_visit.job_id,
    'assignment_count', v_assignment_count,
    'queued_at', v_queued_at
  );

  INSERT INTO public.schedule_visit_transition_requests (
    request_id,
    action,
    visit_id,
    actor_user_id,
    input_hash,
    result
  )
  VALUES (
    p_request_id,
    'enqueue',
    v_visit.id,
    p_actor_user_id,
    v_input_hash,
    v_result
  );

  RETURN QUERY
  SELECT v_visit.id, v_visit.job_id, v_assignment_count, v_queued_at;
END;
$$;

REVOKE ALL ON FUNCTION public.enqueue_schedule_visit_v1(
  UUID, UUID, TEXT, UUID
) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.enqueue_schedule_visit_v1(
  UUID, UUID, TEXT, UUID
) TO service_role;

CREATE OR REPLACE FUNCTION public.schedule_queued_visit_v1(
  p_request_id UUID,
  p_visit_id UUID,
  p_starts_at TIMESTAMPTZ,
  p_actor_user_id UUID
)
RETURNS TABLE (
  visit_id UUID,
  job_id UUID,
  starts_at TIMESTAMPTZ,
  ends_at TIMESTAMPTZ,
  job_start_date DATE,
  job_end_date DATE
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_visit public.schedule_visits%ROWTYPE;
  v_backlog public.schedule_visit_backlog%ROWTYPE;
  v_job_seed public.schedule_jobs%ROWTYPE;
  v_job public.schedule_jobs%ROWTYPE;
  v_quote public.quotes%ROWTYPE;
  v_existing public.schedule_visit_transition_requests%ROWTYPE;
  v_target_date DATE;
  v_new_start DATE;
  v_new_end DATE;
  v_resolved_ends TIMESTAMPTZ;
  v_input_hash TEXT;
