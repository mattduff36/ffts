CREATE OR REPLACE FUNCTION public.schedule_visit_backlog_fingerprint_v1(
  p_visit_id UUID
)
RETURNS TEXT
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  SELECT md5(
    concat_ws(
      '|',
      visit.id::TEXT,
      visit.updated_at::TEXT,
      job.updated_at::TEXT,
      job.status::TEXT,
      COALESCE(quote.updated_at::TEXT, ''),
      COALESCE(quote.status::TEXT, ''),
      COALESCE(quote.commercial_status::TEXT, ''),
      COALESCE(quote.is_latest_version::TEXT, ''),
      COALESCE(quote.accepted::TEXT, ''),
      COALESCE(quote.start_date::TEXT, ''),
      COALESCE(quote.estimated_duration_days::TEXT, ''),
      COALESCE(
        (
          SELECT string_agg(
            assignment.id::TEXT || ':' || assignment.updated_at::TEXT,
            ',' ORDER BY assignment.id
          )
          FROM public.schedule_employee_assignments AS assignment
          WHERE assignment.visit_id = visit.id
        ),
        ''
      ),
      COALESCE(
        (
          SELECT string_agg(
            assignment.id::TEXT || ':' || assignment.updated_at::TEXT,
            ',' ORDER BY assignment.id
          )
          FROM public.schedule_plant_assignments AS assignment
          WHERE assignment.visit_id = visit.id
        ),
        ''
      )
    )
  )
  FROM public.schedule_visits AS visit
  JOIN public.schedule_jobs AS job ON job.id = visit.job_id
  LEFT JOIN public.quotes AS quote ON quote.id = job.quote_id
  WHERE visit.id = p_visit_id;
$$;

